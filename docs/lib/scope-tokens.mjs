/* The design system's tokens are written for :root, and some names (--radius-*, --ease-*, --leading-*)
   are ones Tailwind also defines, while utilities.css restyles :focus-visible and * globally. Rewrite the
   token files so everything lives under .lanre-preview: inside a preview the components look exactly as
   they do in Storybook, and the docs chrome around them keeps Fumadocs' own values. */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

export const SCOPE = '.lanre-preview';
const FILES = ['colors', 'typography', 'spacing', 'effects', 'worlds', 'gems', 'utilities', 'media'];

function scopeSelector(selector) {
  const s = selector.trim();
  if (s === ':root') return SCOPE;
  if (/^\[data-world="[a-z_]+"\]$/.test(s)) return `${SCOPE}${s}, ${SCOPE} ${s}`;
  if (s.startsWith('.mp-')) return s; // namespaced utility classes are safe globally
  if (s === ':focus-visible' || /^\*(::before|::after)?$/.test(s)) return `${SCOPE} ${s}`;
  throw new Error(`scope-tokens: no rule for selector "${s}". Teach docs/lib/scope-tokens.mjs how to scope it.`);
}

/* Walks top-level rules, skipping comments; enough for the plain CSS in tokens/. */
function scopeCss(css) {
  let out = '', i = 0;
  while (i < css.length) {
    if (css.startsWith('/*', i)) { const end = css.indexOf('*/', i) + 2; out += css.slice(i, end); i = end; continue; }
    if (/\s/.test(css[i])) { out += css[i++]; continue; }
    const open = css.indexOf('{', i);
    if (open === -1) throw new Error('scope-tokens: unexpected text after the last rule');
    let depth = 1, j = open + 1;
    for (; j < css.length && depth; j++) {
      if (css.startsWith('/*', j)) { j = css.indexOf('*/', j) + 1; continue; }
      if (css[j] === '{') depth++;
      else if (css[j] === '}') depth--;
    }
    const prelude = css.slice(i, open).trim(), body = css.slice(open + 1, j - 1);
    if (prelude.startsWith('@keyframes')) out += css.slice(i, j);
    else if (prelude.startsWith('@media') || prelude.startsWith('@supports')) out += `${prelude} {${scopeCss(body)}}`;
    else out += `${prelude.split(',').map(scopeSelector).join(', ')} {${body}}`;
    i = j;
  }
  return out;
}

export function writeScopedTokens(tokensDir, outFile) {
  const css = FILES.map(name => `/* ---- tokens/${name}.css ---- */\n` + scopeCss(readFileSync(path.join(tokensDir, `${name}.css`), 'utf8'))).join('\n\n');
  const output = `/* Generated by docs/lib/scope-tokens.mjs from tokens/*.css. Do not edit: change the tokens instead. */\n\n${css}\n`;
  if (!existsSync(outFile) || readFileSync(outFile, 'utf8') !== output) writeFileSync(outFile, output);
}
